#!/usr/bin/env python3
"""Write the AUR package `quill-bin` for one Quill release.

    packaging/aur/make-pkgbuild.py 2026.1104.5000 OUT_DIR

OUT_DIR/PKGBUILD repackages the release's quill-linux-<arch>-bundle.tar.gz
(x86_64 and aarch64) into /usr/lib/quill, with /usr/bin/quill, the desktop
entry and the icons. An install under /usr is package-managed, so Quill's own
updater stays off and pacman updates it. The checksums come from the
release's SHA256SUMS.txt, or from QUILL_SUMS_FILE on disk. `makepkg
--printsrcinfo > .SRCINFO` in OUT_DIR writes the metadata the AUR reads.
docs/decisions/distribution-channels.md
"""
import os
import re
import sys
import urllib.request
from pathlib import Path

REPO = "shinycake/quill"
ARCHES = ("x86_64", "aarch64")

PKGBUILD = """# Maintainer: shinycake <https://github.com/shinycake>
# Generated by packaging/aur/make-pkgbuild.py in https://github.com/{repo}
# for every stable release. Edit the generator, not this file.

pkgname=quill-bin
pkgver={version}
pkgrel=1
pkgdesc="Independent, unofficial Telegram desktop client written in Rust with GPUI and TDLib"
arch=('x86_64' 'aarch64')
url="https://shinycake.github.io/quill/"
license=('MIT' 'LGPL-3.0-only' 'LGPL-2.1-or-later' 'BSL-1.0')
depends=(
  'alsa-lib' 'cairo' 'fontconfig' 'freetype2' 'gcc-libs' 'gdk-pixbuf2' 'glib2' 'glibc'
  'gtk3' 'hicolor-icon-theme' 'libpulse' 'libx11' 'libxcb' 'libxcomposite'
  'libxdamage' 'libxext' 'libxfixes' 'libxkbcommon' 'libxkbcommon-x11'
  'libxrandr' 'libxtst' 'vulkan-driver' 'vulkan-icd-loader' 'wayland' 'zlib'
)
optdepends=(
  'webkit2gtk-4.1: bot mini apps'
  'libsoup3: bot mini apps'
  'ffmpeg: editing and sending videos, video stickers'
  'pipewire: screen sharing in calls'
  'xdg-desktop-portal: screen sharing and file pickers'
)
provides=('quill')
conflicts=('quill')
options=('!strip' '!debug')
source_x86_64=("quill-linux-x86_64-$pkgver.tar.gz::https://github.com/{repo}/releases/download/v$pkgver/quill-linux-x86_64-bundle.tar.gz")
source_aarch64=("quill-linux-aarch64-$pkgver.tar.gz::https://github.com/{repo}/releases/download/v$pkgver/quill-linux-aarch64-bundle.tar.gz")
sha256sums_x86_64=('{sum_x86_64}')
sha256sums_aarch64=('{sum_aarch64}')

package() {{
  local src="$srcdir/quill-linux-$CARCH"
  install -d "$pkgdir/usr/lib/quill" "$pkgdir/usr/bin"
  cp -a "$src/." "$pkgdir/usr/lib/quill/"
  # The bundle's own installer and per-user instructions do not apply here.
  rm -f "$pkgdir/usr/lib/quill/install.sh" "$pkgdir/usr/lib/quill/README.txt"
  rm -rf "$pkgdir/usr/lib/quill/share"
  ln -s /usr/lib/quill/quill "$pkgdir/usr/bin/quill"
  install -Dm644 "$src/share/applications/org.shinycake.quill.desktop" \\
    "$pkgdir/usr/share/applications/org.shinycake.quill.desktop"
  local icon size
  for icon in "$src"/share/icons/hicolor/*/apps/quill.png; do
    size="$(basename "$(dirname "$(dirname "$icon")")")"
    install -Dm644 "$icon" "$pkgdir/usr/share/icons/hicolor/$size/apps/quill.png"
  done
  install -d "$pkgdir/usr/share/licenses/$pkgname"
  ln -s /usr/lib/quill/LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  ln -s /usr/lib/quill/THIRD_PARTY.md "$pkgdir/usr/share/licenses/$pkgname/THIRD_PARTY.md"
  ln -s /usr/lib/quill/licenses "$pkgdir/usr/share/licenses/$pkgname/licenses"
}}
"""


def release_sums(version: str) -> dict[str, str]:
    path = os.environ.get("QUILL_SUMS_FILE")
    if path:
        text = Path(path).read_text()
    else:
        url = f"https://github.com/{REPO}/releases/download/v{version}/SHA256SUMS.txt"
        with urllib.request.urlopen(url, timeout=60) as response:
            text = response.read().decode()
    sums = {}
    for line in text.splitlines():
        parts = line.split()
        if len(parts) == 2:
            sums[parts[1].lstrip("*")] = parts[0]
    return sums


def main() -> int:
    if len(sys.argv) != 3 or not re.fullmatch(r"\d{4}\.\d{3,4}\.\d+", sys.argv[1]):
        print(__doc__, file=sys.stderr)
        return 2
    version, out = sys.argv[1], Path(sys.argv[2])
    sums = release_sums(version)
    fields = {"repo": REPO, "version": version}
    for arch in ARCHES:
        asset = f"quill-linux-{arch}-bundle.tar.gz"
        digest = sums.get(asset, "")
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            print(f"no SHA-256 for {asset} in the release's SHA256SUMS.txt", file=sys.stderr)
            return 1
        fields[f"sum_{arch}"] = digest
    out.mkdir(parents=True, exist_ok=True)
    (out / "PKGBUILD").write_text(PKGBUILD.format(**fields))
    return 0


if __name__ == "__main__":
    sys.exit(main())
